-- ─────────────────────────────────────────── 소식 본문을 버린다
--
-- 수집기가 기사 전문(body)과 본문 속 이미지 주소(images)를 담아 왔다. 앱은 오래전부터
-- 제목까지만 보여 주고 읽는 것은 원문 페이지로 넘기는데, 표에는 전문이 그대로 쌓였다.
-- 기사는 남의 저작물이라 화면에 안 보여도 우리 DB 에 담는 것 자체가 복제다.
--
-- 비우지 않고 칸째 지운다. 칸이 남아 있으면 누군가 다시 채운다.
--
-- 순서가 있다: 본문을 안 받는 collect-news 를 **먼저** 배포한 뒤에 돌린다. 옛 수집기는
-- body 칸을 찾다 크론마다 실패한다. 앱은 목록을 칸 이름으로, 상세를 * 로 받으므로 이미
-- 깔린 빌드도 깨지지 않는다.
--
-- 다시 돌려도 깨지지 않게 쓴다. 부분 인덱스(news_pending_body_idx)는 칸과 함께 사라진다.

alter table public.news
  drop column if exists body,
  drop column if exists images;
